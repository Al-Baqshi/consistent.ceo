// Holds the spawned gateway sidecar's child handle so it can be killed on
// tray quit or when the main window closes.
#[derive(Default)]
struct GatewayProcess(Arc<Mutex<Option<tauri_plugin_shell::process::CommandChild>>>);

// Idempotent: writes DEFAULT_CONFIG only the first time, so relaunching the
// app never clobbers settings the user has since edited.
fn ensure_config_path(app: &tauri::AppHandle) -> std::io::Result<std::path::PathBuf> {
    let app_data = app
        .path()
        .app_data_dir()
        .map_err(|e| std::io::Error::other(e.to_string()))?;
    std::fs::create_dir_all(&app_data)?;
    let config_path = app_data.join("consistent_world.toml");
    if !config_path.exists() {
        std::fs::write(&config_path, DEFAULT_CONFIG)?;
    }
    Ok(config_path)
}

/// Read the gateway's local auth token from the file it provisions next to the
/// config (`gateway_auth_token`). The gateway writes this before it starts
/// serving, so by the time `/health` responds the file exists. Returns `None`
/// if the file is absent or empty (e.g. a keyring-configured token).
fn read_auth_token(config_path: &Path) -> Option<String> {
    let token_path = config_path.parent()?.join("gateway_auth_token");
    let raw = std::fs::read_to_string(token_path).ok()?;
    let trimmed = raw.trim();
    if trimmed.is_empty() {
        None
    } else {
        Some(trimmed.to_string())
    }
}

/// Wait for the gateway, probing the *same origin the window will load*.
///
/// That is `localhost`, while the gateway binds `127.0.0.1`. Those are the same
/// machine but not the same name, and on a host where `localhost` resolves to
/// `::1` first the browser's fallback is what saves it. Probing the real origin
/// means a resolution problem shows up here, as a startup message, rather than
/// as a blank window nobody can explain.
fn wait_for_gateway(timeout_secs: u64) -> bool {
    let client = reqwest::blocking::Client::builder()
        .timeout(Duration::from_secs(2))
        .build()
        .unwrap();
    let deadline = std::time::Instant::now() + Duration::from_secs(timeout_secs);
    let url = format!("{}/health", login::GATEWAY_ORIGIN);
    while std::time::Instant::now() < deadline {
        if let Ok(res) = client.get(&url).send() {
            if res.status().is_success() {
                return true;
            }
        }
        std::thread::sleep(Duration::from_millis(300));
    }
    false
}

fn toggle_main_window(app: &tauri::AppHandle) {
    if let Some(window) = app.get_webview_window("main") {
        match window.is_visible() {
            Ok(true) => {
                let _ = window.hide();
            }
            _ => {
                let _ = window.show();
                let _ = window.set_focus();
            }
        }
    }
}

/// Stop everything this process started, before quitting or restarting.
/// Returns whether it stopped a gateway this process had spawned.
fn stop_children(app: &tauri::AppHandle) -> bool {
    let mut stopped_gateway = false;
    if let Some(state) = app.try_state::<GatewayProcess>() {
        if let Ok(mut guard) = state.0.lock() {
            if let Some(child) = guard.take() {
                stopped_gateway = child.kill().is_ok();
            }
        }
    }
    // Embedded terminals are children of this process; without this a shell
    // (or a half-finished `codex login`) would be orphaned with its PTY when
    // the app goes away.
    if let Some(pty) = app.try_state::<PtySessions>() {
        pty.kill_all();
    }
    stopped_gateway
}

/// The tray menu: show/hide/quit, plus "Restart to update" once an update is
/// installed and waiting (`updater.rs`).
fn tray_menu(app: &tauri::AppHandle) -> tauri::Result<Menu<tauri::Wry>> {
    let show = MenuItem::with_id(app, "show", "Show Consistent", true, None::<&str>)?;
    let hide = MenuItem::with_id(app, "hide", "Hide Window", true, None::<&str>)?;
    let quit = MenuItem::with_id(app, "quit", "Quit", true, None::<&str>)?;
    let pending = app.try_state::<PendingUpdate>().and_then(|p| p.version());
    match pending {
        Some(version) => {
            let restart = MenuItem::with_id(
                app,
                "restart_update",
                format!("Restart to update to {version}"),
                true,
                None::<&str>,
            )?;
            Menu::with_items(app, &[&restart, &show, &hide, &quit])
        }
        None => Menu::with_items(app, &[&show, &hide, &quit]),
    }
}

/// Rebuild the tray menu, e.g. when an update becomes ready.
pub(crate) fn refresh_tray_menu(app: &tauri::AppHandle) {
    if let (Some(tray), Ok(menu)) = (app.tray_by_id("consistent-world-tray"), tray_menu(app)) {
        let _ = tray.set_menu(Some(menu));
    }
}

// Sets up the OS tray icon; quit kills the gateway sidecar before exiting, and
// "Restart to update" does the same before relaunching into the new version.
fn build_tray(app: &tauri::AppHandle) -> tauri::Result<()> {
    let menu = tray_menu(app)?;

    TrayIconBuilder::with_id("consistent-world-tray")
        .tooltip("Consistent")
        .menu(&menu)
        .show_menu_on_left_click(true)
        .on_menu_event(|app, event| match event.id.as_ref() {
            "show" => {
                if let Some(w) = app.get_webview_window("main") {
                    let _ = w.show();
                    let _ = w.set_focus();
                }
            }
            "hide" => {
                if let Some(w) = app.get_webview_window("main") {
                    let _ = w.hide();
                }
            }
            "restart_update" => {
                // The new version probes the port and attaches to any gateway
                // it finds; wait for ours to let go, or it would attach to a
                // dying process and be left with none.
                if stop_children(app) {
                    for _ in 0..25 {
                        if !gateway_already_running() {
                            break;
                        }
                        std::thread::sleep(Duration::from_millis(200));
                    }
                }
                app.restart();
            }
            "quit" => {
                let _ = stop_children(app);
                app.exit(0);
            }
            _ => {}
        })
        .build(app)?;
    Ok(())
}

/// Is a gateway already serving on the local port? Short timeout: this runs on
/// the UI startup path, and "no answer quickly" is the same as "nothing there".
fn gateway_already_running() -> bool {
    reqwest::blocking::Client::builder()
        .timeout(Duration::from_millis(700))
        .build()
        .ok()
        .and_then(|c| c.get("http://127.0.0.1:18800/health").send().ok())
        .map(|r| r.status().is_success())
        .unwrap_or(false)
}

fn main() {
    // Global shortcuts (window toggle, dictation, command mode) are
    // user-configurable — see shortcuts.rs. The handler dispatches through the
    // ShortcutsState lookup table, so rebinding never rebuilds this closure.
    tauri::Builder::default()
        .plugin(tauri_plugin_shell::init())
        .plugin(tauri_plugin_notification::init())
        .plugin(tauri_plugin_updater::Builder::new().build())
        .plugin(tauri_plugin_autostart::init(
            tauri_plugin_autostart::MacosLauncher::LaunchAgent,
            Some(vec![autostart::HIDDEN_ARG]),
        ))
        .plugin(
            tauri_plugin_global_shortcut::Builder::new()
                .with_handler(shortcuts::on_shortcut)
                .build(),
        )
        .manage(GatewayProcess::default())
        .manage(ShortcutsState::default())
        .manage(VoiceProcess::default())
        .manage(DictationProcess::default())
        .manage(GatewayAuth::default())
        .manage(LoginState::default())
        .manage(PtySessions::default())
        .manage(PendingUpdate::default())
        .invoke_handler(tauri::generate_handler![
            voice_start,
            voice_stop,
            login_local,
            login_start,
            open_verification_url,
            login_poll,
            login_cancel,
            dictate_start,
            dictate_stop,
            inject_text,
            injection_trusted,
            open_accessibility_settings,
            set_auto_inject,
            send_to_agent,
            shortcuts_get,
            shortcuts_set,
            shortcuts_reset,
            vault_device_status,
            vault_enroll_device,
            vault_unlock_with_device,
            vault_forget_device,
            vault_revoke_device,
            pty_spawn,
            pty_write,
            pty_resize,
            pty_kill,
            open_signin_url,
            autostart_status,
            autostart_set
        ])
        .setup(move |app| {
            let app_handle = app.handle().clone();
            if let Err(e) = build_tray(&app_handle) {
                eprintln!("Failed to build tray: {e}");
            }
            shortcuts::init(&app_handle);
            autostart::apply_default(&app_handle);
            updater::spawn(app_handle.clone());

            // No external database to start: the gateway runs an embedded,
            // in-process surrealkv store (see DEFAULT_CONFIG [memory].surreal_url).

            let config_path = match ensure_config_path(&app_handle) {
                Ok(p) => p,
                Err(e) => {
                    eprintln!("Failed to prepare config: {}", e);
                    return Ok(());
                }
            };

            // Another gateway may already own the port: a LaunchAgent
            // installed by install.sh, or a `consistent-world start` in a
            // terminal. Spawning a second one means two processes fighting
            // over port 18800 and the same embedded database — so probe first
            // and attach to what is already running.
            if gateway_already_running() {
                println!("Gateway already running on 127.0.0.1:18800; attaching instead of spawning.");
                return Ok(());
            }

            let child = match app_handle.shell().sidecar("consistent-world") {
                Ok(cmd) => {
                    let cmd = cmd
                        .args(["--config", config_path.to_string_lossy().as_ref()])
                        // The gateway loads .env on startup. In this repo, dev .env may point at
                        // a remote SurrealDB, but the desktop product must boot locally.
                        .env("SURREAL_URL", "surrealkv://~/.consistent-world/db")
                        .env("SURREAL_NS", "consistent-world")
                        .env("SURREAL_DB", "gateway");
                    match cmd.spawn() {
                        Ok((_rx, child)) => Some(child),
                        Err(e) => {
                            eprintln!("Failed to spawn gateway sidecar: {}", e);
                            return Ok(());
                        }
                    }
                }
                Err(e) => {
                    eprintln!(
                        "Sidecar 'consistent-world' not found (run build:sidecar first): {}",
                        e
                    );
                    return Ok(());
                }
            };

            if let Some(child) = child {
                let _ = app_handle
                    .state::<GatewayProcess>()
                    .0
                    .lock()
                    .unwrap()
                    .replace(child);
            }

            if !wait_for_gateway(15) {
                eprintln!("Gateway did not become ready in time. Check logs.");
            }

            // Build the main window now that the gateway is up.
            //
            // The webview no longer gets the gateway's static token. That token
            // authenticates as a service principal with no account behind it,
            // and injecting it into sessionStorage meant every page — and any
            // script that ever ran in one — held the machine's skeleton key.
            // The window signs in like any other client, through the loopback
            // browser flow in `login.rs`, and ends up with a real user session.
            //
            // Rust-side callers (spoken commands, notifications) still need to
            // reach the gateway before anyone has signed in, so `GatewayAuth`
            // keeps the static token until `login_poll` replaces it with the
            // user's session.
            let auth_token = read_auth_token(&config_path);
            if auth_token.is_none() {
                eprintln!("No gateway auth token file found; background features may be limited.");
            }
            app_handle.state::<GatewayAuth>().set_token(auth_token);

            // `localhost`, not `127.0.0.1`. WebAuthn scopes credentials to an
            // origin and the gateway's passkey RP id is `localhost`, so a
            // passkey enrolled in the system browser is invisible to a webview
            // loaded from `127.0.0.1` — same machine, different origin. Loading
            // both halves from `localhost` is the only configuration in which
            // passkeys work in the desktop app at all.
            let win_builder = tauri::WebviewWindowBuilder::new(
                &app_handle,
                "main",
                tauri::WebviewUrl::External(
                    format!("{}/loader", login::GATEWAY_ORIGIN).parse().unwrap(),
                ),
            )
            .title("Consistent")
            .inner_size(1200.0, 800.0)
            .min_inner_size(800.0, 600.0)
            // Started at login: live in the tray until someone opens it.
            .visible(!autostart::launched_hidden());
            if let Err(e) = win_builder.build() {
                eprintln!("Failed to build main window: {e}");
            }

            // Native notifications for reminders, approvals, and finished runs.
            // Started after the token is set so the very first poll is
            // authenticated, and it keeps running when the window is closed —
            // which is the whole point of doing this in the shell rather than
            // in the web layer.
            companion::spawn_feed_watcher(app_handle.clone());

            Ok(())
        })
        // Closing the window hides it: the gateway keeps working in the
        // background (missions, heartbeats, the phone's connection), and the
        // tray's Quit is the one way to stop it. Destroying the window (at
        // quit) still kills the gateway sidecar so it is never orphaned.
        .on_window_event(|window, event| {
            if let tauri::WindowEvent::CloseRequested { api, .. } = event {
                if window.label() == "main" {
                    api.prevent_close();
                    let _ = window.hide();
                }
                return;
            }
            if let tauri::WindowEvent::Destroyed = event {
                let app = window.app_handle();
                if let Some(state) = app.try_state::<GatewayProcess>() {
                    if let Some(child) = state.0.lock().unwrap().take() {
                        let _ = child.kill();
                    }
                }
                // The terminals lived in that window; nothing is left to
                // show their output, so end them rather than leak shells.
                if let Some(pty) = app.try_state::<PtySessions>() {
                    pty.kill_all();
                }
            }
        })
        .build(tauri::generate_context!())
        .expect("error while building tauri application")
        .run(|app, event| {
            // macOS: clicking the Dock icon brings back a hidden window.
            #[cfg(target_os = "macos")]
            if let tauri::RunEvent::Reopen { .. } = event {
                if let Some(w) = app.get_webview_window("main") {
                    let _ = w.show();
                    let _ = w.set_focus();
                }
            }
            #[cfg(not(target_os = "macos"))]
            let _ = (app, event);
        });
}
